"""Train a compact 12-band smoke-plume classifier on the Zenodo scenes.

The default model is intentionally small for CPU-only execution. It is a
ThermoScope baseline, not an exact reproduction of the paper's ResNet-50.
The split is site-grouped and generated by prepare_smoke_dataset.py.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import random
import time
from datetime import datetime, timezone
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import rasterio
import torch
from sklearn.metrics import (average_precision_score, confusion_matrix, f1_score,
                             precision_recall_fscore_support, roc_auc_score)
from torch import nn
from torch.utils.data import DataLoader, Dataset

from src.thermoscope_app.smoke_model import (
    CHANNEL_MEANS, CHANNEL_STDS, MODEL_BAND_INDEXES, build_tiny_smoke_cnn,
)


class SmokeDataset(Dataset):
    def __init__(self, rows: pd.DataFrame, dataset_dir: Path, *, training: bool):
        self.rows = rows.reset_index(drop=True)
        self.dataset_dir = dataset_dir
        self.training = training

    def __len__(self) -> int:
        return len(self.rows)

    def __getitem__(self, index: int):
        row = self.rows.iloc[index]
        path = self.dataset_dir / Path(str(row.source_relative_path))
        with rasterio.open(path) as dataset:
            array = dataset.read(MODEL_BAND_INDEXES).astype(np.float32)
        if array.shape[1] > 120 or array.shape[2] > 120:
            top, left = max(0, (array.shape[1] - 120) // 2), max(0, (array.shape[2] - 120) // 2)
            array = array[:, top:top + 120, left:left + 120]
        array = np.pad(array, ((0, 0), (0, 120 - array.shape[1]), (0, 120 - array.shape[2])), mode="edge")
        array = (array - CHANNEL_MEANS[:, None, None]) / CHANNEL_STDS[:, None, None]
        if self.training:
            top, left = random.randrange(31), random.randrange(31)
            array = array[:, top:top + 90, left:left + 90]
            if random.random() < .5:
                array = array[:, :, ::-1]
            if random.random() < .5:
                array = array[:, ::-1, :]
            array = np.rot90(array, random.randrange(4), axes=(1, 2))
        else:
            array = array[:, 15:105, 15:105]
        x = torch.from_numpy(np.ascontiguousarray(array, dtype=np.float32))
        y = torch.tensor(float(row.label), dtype=torch.float32)
        return x, y


def _metrics(y_true: np.ndarray, scores: np.ndarray, threshold: float) -> dict[str, object]:
    predicted = (scores >= threshold).astype(int)
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_true, predicted, labels=[0, 1], zero_division=0
    )
    matrix = confusion_matrix(y_true, predicted, labels=[0, 1])
    return {
        "threshold": threshold,
        "accuracy": float((predicted == y_true).mean()),
        "precision_negative": float(precision[0]), "recall_negative": float(recall[0]), "f1_negative": float(f1[0]),
        "precision_positive": float(precision[1]), "recall_positive": float(recall[1]), "f1_positive": float(f1[1]),
        "macro_f1": float(f1_score(y_true, predicted, average="macro", zero_division=0)),
        "roc_auc": float(roc_auc_score(y_true, scores)) if len(np.unique(y_true)) == 2 else None,
        "average_precision": float(average_precision_score(y_true, scores)) if len(np.unique(y_true)) == 2 else None,
        "confusion_matrix_rows_true_0_1_cols_pred_0_1": matrix.tolist(),
    }


def _select_training_rows(rows: pd.DataFrame, limit: int, seed: int) -> pd.DataFrame:
    if not limit or len(rows) <= limit:
        return rows
    # Maintain a balanced training subset while sampling across the available
    # training locations. Geographic test/validation groups remain untouched.
    per_class = max(1, limit // 2)
    selected = []
    for label in (0, 1):
        class_rows = rows[rows.label == label]
        count = min(per_class, len(class_rows))
        selected.append(class_rows.sample(n=count, random_state=seed + int(label)))
    result = pd.concat(selected).sample(frac=1, random_state=seed).reset_index(drop=True)
    return result


def train(manifest_path: Path, dataset_dir: Path, output_dir: Path, model_path: Path,
          *, epochs: int = 5, batch_size: int = 4, max_train_images: int = 4000,
          seed: int = 20261117) -> dict[str, object]:
    for path in (output_dir, model_path, model_path.with_suffix(".json")):
        if path.exists():
            raise FileExistsError(f"Refusing to overwrite existing output: {path}")
    if epochs < 1 or batch_size < 1:
        raise ValueError("epochs and batch_size must be positive")
    manifest = pd.read_csv(manifest_path)
    if manifest.empty or not {"split", "site_group_id", "label", "source_relative_path"}.issubset(manifest):
        raise ValueError("Dataset manifest is empty or missing required fields")
    splits = {name: manifest[manifest.split == name].copy() for name in ("train", "validation", "test")}
    if any(rows.empty for rows in splits.values()):
        raise ValueError("Train, validation, and test splits must all contain samples")
    if any(set(splits[a].site_group_id) & set(splits[b].site_group_id)
           for a, b in (("train", "validation"), ("train", "test"), ("validation", "test"))):
        raise ValueError("Location leakage detected across splits")

    torch.manual_seed(seed)
    np.random.seed(seed)
    random.seed(seed)
    torch.set_num_threads(min(4, torch.get_num_threads()))
    train_rows = _select_training_rows(splits["train"], max_train_images, seed)
    train_set = SmokeDataset(train_rows, dataset_dir, training=True)
    val_set = SmokeDataset(splits["validation"], dataset_dir, training=False)
    test_set = SmokeDataset(splits["test"], dataset_dir, training=False)
    # Single-process loaders avoid worker-process RAM multiplication on Windows.
    train_loader = DataLoader(train_set, batch_size=batch_size, shuffle=True, num_workers=0)
    val_loader = DataLoader(val_set, batch_size=batch_size, shuffle=False, num_workers=0)
    test_loader = DataLoader(test_set, batch_size=batch_size, shuffle=False, num_workers=0)
    model = build_tiny_smoke_cnn()
    optimizer = torch.optim.AdamW(model.parameters(), lr=1e-3, weight_decay=1e-4)
    positives = max(int((train_rows.label == 1).sum()), 1)
    negatives = max(int((train_rows.label == 0).sum()), 1)
    loss_fn = nn.BCEWithLogitsLoss(pos_weight=torch.tensor([negatives / positives], dtype=torch.float32))
    history: list[dict[str, float]] = []
    best_state: dict[str, torch.Tensor] | None = None
    best_val_loss = float("inf")
    started = time.monotonic()

    for epoch in range(epochs):
        model.train()
        loss_total, seen = 0.0, 0
        for x, y in train_loader:
            optimizer.zero_grad(set_to_none=True)
            logits = model(x).reshape(-1)
            loss = loss_fn(logits, y)
            loss.backward()
            optimizer.step()
            loss_total += float(loss.item()) * len(y)
            seen += len(y)
        model.eval()
        val_loss_total, val_seen = 0.0, 0
        with torch.inference_mode():
            for x, y in val_loader:
                logits = model(x).reshape(-1)
                loss = loss_fn(logits, y)
                val_loss_total += float(loss.item()) * len(y)
                val_seen += len(y)
        train_loss, val_loss = loss_total / max(seen, 1), val_loss_total / max(val_seen, 1)
        history.append({"epoch": epoch + 1, "train_loss": train_loss, "validation_loss": val_loss})
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            best_state = {key: value.detach().cpu().clone() for key, value in model.state_dict().items()}
        print(f"epoch={epoch + 1}/{epochs} train_loss={train_loss:.5f} validation_loss={val_loss:.5f}", flush=True)
    if best_state is None:
        raise RuntimeError("Training did not produce a checkpoint")
    model.load_state_dict(best_state)
    model.eval()

    def infer(loader: DataLoader) -> tuple[np.ndarray, np.ndarray]:
        labels, scores = [], []
        with torch.inference_mode():
            for x, y in loader:
                logits = model(x).reshape(-1)
                labels.extend(y.numpy().astype(int).tolist())
                scores.extend(torch.sigmoid(logits).numpy().astype(float).tolist())
        return np.asarray(labels, dtype=int), np.asarray(scores, dtype=float)

    y_val, score_val = infer(val_loader)
    threshold_grid = np.linspace(.05, .95, 91)
    threshold = max(threshold_grid, key=lambda value: f1_score(y_val, score_val >= value, zero_division=0))
    y_test, score_test = infer(test_loader)
    test_metrics = _metrics(y_test, score_test, float(threshold))
    majority_prediction = int(splits["train"].label.mean() >= .5)
    baseline_metrics = _metrics(y_test, np.full(len(y_test), float(majority_prediction)), .5)

    output_dir.mkdir(parents=True)
    model_path.parent.mkdir(parents=True, exist_ok=True)
    if model_path.exists() or model_path.with_suffix(".json").exists():
        raise FileExistsError("Model checkpoint/config was created during training; refusing to overwrite")
    temp_model = model_path.with_name(model_path.name + ".tmp")
    torch.save(best_state, temp_model)
    temp_model.replace(model_path)
    manifest_sha = hashlib.sha256(manifest_path.read_bytes()).hexdigest()
    archive_manifest = dataset_dir.parent.parent / "raw" / "industrial_smoke_zenodo_v1" / "acquisition_manifest.json"
    archive_info = json.loads(archive_manifest.read_text(encoding="utf-8")) if archive_manifest.is_file() else {}
    config = {
        "architecture": "thermoscope_tiny_cnn_12band", "model_name": "ThermoScope visible-smoke TinyCNN v1",
        "task": "manual visible smoke plume presence in Sentinel-2 scene", "classes": ["no_visible_smoke", "visible_smoke"],
        "input_channels": 12, "source_band_indexes_1based": list(MODEL_BAND_INDEXES),
        "source_band_order": ["B01", "B02", "B03", "B04", "B05", "B06", "B07", "B08", "B8A", "B09", "B11", "B12"],
        "normalization_mean": CHANNEL_MEANS.tolist(), "normalization_std": CHANNEL_STDS.tolist(),
        "crop_size": 90, "small_chip_padding": "edge replication to 120x120",
        "decision_threshold": float(threshold), "threshold_method": "maximum positive-class F1 on validation split",
        "score_is_calibrated_probability": False, "seed": seed, "epochs": epochs,
        "batch_size": batch_size, "max_train_images": max_train_images, "actual_train_images": len(train_rows),
        "optimizer": "AdamW", "learning_rate": 1e-3, "positive_class_weight": negatives / positives,
        "split_file": str(manifest_path), "split_manifest_sha256": manifest_sha,
        "split_method": "site-grouped seeded split created for ThermoScope; original site assignment unavailable",
        "dataset_archive_sha256": next((f["sha256"] for f in archive_info.get("files", []) if f.get("file") == "images.tar.gz"), None),
        "software": {"python": __import__("platform").python_version(), "torch": torch.__version__,
                     "numpy": np.__version__, "pandas": pd.__version__},
        "trained_at_utc": datetime.now(timezone.utc).isoformat(),
        "runtime_seconds": round(time.monotonic() - started, 3),
        "scientific_limit": "European 2019 visible-smoke dataset; not fire, causality, thermal-source or Jharkhand validation.",
    }
    model_path.with_suffix(".json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    output_dir.joinpath("training_history.csv").write_text(
        pd.DataFrame(history).to_csv(index=False), encoding="utf-8"
    )
    result = {
        "task": config["task"], "label_counts": {"train_subset": train_rows.label.value_counts().to_dict(),
                        "validation": splits["validation"].label.value_counts().to_dict(),
                        "test": splits["test"].label.value_counts().to_dict()},
        "site_counts": {name: int(rows.site_group_id.nunique()) for name, rows in splits.items()},
        "baseline_majority": baseline_metrics, "smoke_model": test_metrics,
        "interpretation": "Metrics are against the dataset's manual visible-smoke labels on a new location-held-out split. They are not fire-detection metrics and are not the paper's reported test scores.",
    }
    (output_dir / "evaluation_metrics.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    (output_dir / "validation_scores.csv").write_text(
        pd.DataFrame({"label": y_val, "smoke_score_uncalibrated": score_val}).to_csv(index=False), encoding="utf-8"
    )
    (output_dir / "test_predictions.csv").write_text(
        pd.DataFrame({"label": y_test, "smoke_score_uncalibrated": score_test,
                      "prediction": (score_test >= threshold).astype(int)}).to_csv(index=False), encoding="utf-8"
    )
    figure, axes = plt.subplots(1, 2, figsize=(9, 4))
    axes[0].plot([row["epoch"] for row in history], [row["train_loss"] for row in history], label="Train")
    axes[0].plot([row["epoch"] for row in history], [row["validation_loss"] for row in history], label="Validation")
    axes[0].set(xlabel="Epoch", ylabel="BCE loss", title="Loss history")
    axes[0].legend()
    matrix = np.asarray(test_metrics["confusion_matrix_rows_true_0_1_cols_pred_0_1"])
    axes[1].imshow(matrix, cmap="Blues")
    axes[1].set(xticks=[0, 1], yticks=[0, 1], xlabel="Predicted", ylabel="Manual label", title="Location-held-out test")
    for (i, j), value in np.ndenumerate(matrix):
        axes[1].text(j, i, str(value), ha="center", va="center")
    figure.tight_layout()
    figure.savefig(output_dir / "training_evaluation.png", dpi=180)
    plt.close(figure)
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--dataset-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--model-path", type=Path, required=True)
    parser.add_argument("--epochs", type=int, default=5)
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument("--max-train-images", type=int, default=4000,
                        help="Balanced deterministic cap; use 0 to train on the full train split")
    parser.add_argument("--seed", type=int, default=20261117)
    args = parser.parse_args()
    result = train(args.manifest, args.dataset_dir, args.output_dir, args.model_path,
                   epochs=args.epochs, batch_size=args.batch_size,
                   max_train_images=args.max_train_images, seed=args.seed)
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
